function fitText(ctx, text, maxWidth, px, weight, family){
  // shrink until it fits, so long titles never overflow the card
  var size = px;
  do {
    ctx.font = weight+' '+size+'px '+family;
    if(ctx.measureText(text).width <= maxWidth) break;
    size -= 1;
  } while(size > px*0.5);
  return size;
}
function drawCardMap(ctx, rect, pal, theme){
  var m = currentMetric();
  var proj = d3.geoNaturalEarth1().fitExtent([[rect.x,rect.y],[rect.x+rect.w,rect.y+rect.h]], GEO);
  var path = d3.geoPath(proj, ctx);
  GEO.features.forEach(function(f){
    var c = byIso[f.id];
    var fill = (c && c[m.key]!=null) ? colorForMetric(m, c[m.key], theme) : pal.noData;
    ctx.beginPath(); path(f);
    ctx.fillStyle = fill; ctx.fill();
    ctx.strokeStyle = pal.bg; ctx.lineWidth = 0.75; ctx.stroke();
  });
  var outline = function(iso, color, width){
    var f = featureById[iso];
    if(!f) return;
    ctx.beginPath(); path(f);
    ctx.strokeStyle = pal.bg; ctx.lineWidth = width+2.5; ctx.lineJoin='round'; ctx.stroke();
    ctx.beginPath(); path(f);
    ctx.strokeStyle = color; ctx.lineWidth = width; ctx.stroke();
  };
  state.pinned.forEach(function(iso, i){ outline(iso, pal.cats[i], 2.5); });
  if(state.selectedIso && pinIndex(state.selectedIso)<0) outline(state.selectedIso, pal.text, 2.5);
}
