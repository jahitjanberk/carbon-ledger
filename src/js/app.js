function initMapGeometry(){
  projection.fitExtent([[8,8],[952,502]], GEO);
  var g = svg.append('g').attr('id','countries-g');
  g.selectAll('path.country-path')
    .data(GEO.features, function(d){ return d.id; })
    .enter().append('path')
    .attr('class','country-path')
    .attr('d', pathGen)
    .attr('data-iso', function(d){ return d.id; })
    .on('mousemove', onCountryHover)
    .on('mouseleave', hideMapTooltip)
    .on('click', function(ev,d){
      var c = byIso[d.id];
      if(!c || c.co2==null) return;
      if(ev.shiftKey){ togglePin(d.id); return; }
      selectCountry(d.id);
    });
  mapReady = true;
}

function renderMap(){
  if(!mapReady) initMapGeometry();
  var theme = effectiveTheme();
  var m = currentMetric();
  svg.selectAll('path.country-path')
    .classed('no-data', function(d){ var c=byIso[d.id]; return !c || c[m.key]==null; })
    .classed('selected', function(d){ return d.id===state.selectedIso; })
    .classed('pinned', function(d){ return pinIndex(d.id)>=0; })
    .style('fill', function(d){
      var c = byIso[d.id];
      if(!c || c[m.key]==null) return null;
      return colorForMetric(m, c[m.key], theme);
    });
  // Pinned countries get an outline drawn in a top overlay group: a casing
  // ring in the page background under the slot color, so the outline reads
  // against any choropleth fill (a blue ring on a dark-blue fill would vanish).
  var overlay = svg.select('#pin-overlay');
  if(overlay.empty()) overlay = svg.append('g').attr('id','pin-overlay').attr('pointer-events','none');
  overlay.selectAll('*').remove();
  state.pinned.forEach(function(iso, i){
    var f = featureById[iso];
    if(!f) return;
    var d = pathGen(f);
    overlay.append('path').attr('d', d).attr('fill','none')
      .attr('stroke','var(--page-bg)').attr('stroke-width',3.4).attr('stroke-linejoin','round');
    overlay.append('path').attr('d', d).attr('fill','none')
      .attr('stroke','var('+CAT_HEX[i]+')').attr('stroke-width',1.7).attr('stroke-linejoin','round');
  });
}

