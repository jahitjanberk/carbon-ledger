function fitText(ctx, text, maxWidth, px, weight, family){
  // shrink until it fits, so long titles never overflow the card
  var size = px;
  do {
    ctx.font = weight+' '+size+'px '+family;
    if(ctx.measureText(text).width <= maxWidth) break;
    size -= 1;
  } while(size > px*0.5);
  return size;
}
function drawCardMap(ctx, rect, pal, theme){
  var m = currentMetric();
  var proj = d3.geoNaturalEarth1().fitExtent([[rect.x,rect.y],[rect.x+rect.w,rect.y+rect.h]], GEO);
  var path = d3.geoPath(proj, ctx);
  GEO.features.forEach(function(f){
    var c = byIso[f.id];
    var fill = (c && c[m.key]!=null) ? colorForMetric(m, c[m.key], theme) : pal.noData;
    ctx.beginPath(); path(f);
    ctx.fillStyle = fill; ctx.fill();
    ctx.strokeStyle = pal.bg; ctx.lineWidth = 0.75; ctx.stroke();
  });
  var outline = function(iso, color, width){
    var f = featureById[iso];
    if(!f) return;
    ctx.beginPath(); path(f);
    ctx.strokeStyle = pal.bg; ctx.lineWidth = width+2.5; ctx.lineJoin='round'; ctx.stroke();
    ctx.beginPath(); path(f);
    ctx.strokeStyle = color; ctx.lineWidth = width; ctx.stroke();
  };
  state.pinned.forEach(function(iso, i){ outline(iso, pal.cats[i], 2.5); });
  if(state.selectedIso && pinIndex(state.selectedIso)<0) outline(state.selectedIso, pal.text, 2.5);
}
function buildShareCard(sizeKey){
  var size = SHARE_SIZES[sizeKey];
  var W = size.w, H = size.h;
  var cv = document.createElement('canvas'); cv.width = W; cv.height = H;
  var ctx = cv.getContext('2d');
  var pal = cardPalette();
  var theme = effectiveTheme();
  var m = currentMetric();
  var view = shareCardView();
  var SANS = '"Inter", system-ui, -apple-system, sans-serif';
  var MONO = '"IBM Plex Mono", ui-monospace, monospace';
  var P = Math.round(H*0.075);

  ctx.fillStyle = pal.bg;
  ctx.fillRect(0,0,W,H);
  // brand hairline across the top, matching the logo's gradient dot
  var grad = ctx.createLinearGradient(0,0,W,0);
  grad.addColorStop(0, pal.cats[0]); grad.addColorStop(1, pal.cats[2]);
  ctx.fillStyle = grad;
  ctx.fillRect(0,0,W,Math.max(4,H*0.008));

  // header: brand + data vintage
  var hy = P*0.9;
  ctx.beginPath(); ctx.arc(P+H*0.011, hy-H*0.011, H*0.011, 0, Math.PI*2);
  ctx.fillStyle = pal.cats[0]; ctx.fill();
  ctx.fillStyle = pal.sec;
  ctx.font = '700 '+Math.round(H*0.03)+'px '+SANS;
  ctx.textBaseline = 'alphabetic';
  ctx.fillText('Carbon Ledger', P+H*0.034, hy);
  ctx.textAlign = 'right';
  ctx.font = '500 '+Math.round(H*0.024)+'px '+MONO;
  ctx.fillStyle = pal.muted;
  ctx.fillText('Data through '+LATEST_YEAR, W-P, hy);
  ctx.textAlign = 'left';

  // title + subtitle
  var title, subtitle;
  if(view==='global'){
    title = m.mapLabel+', '+LATEST_YEAR;
    subtitle = 'All countries · '+m.legendUnit;
  } else if(view==='country'){
    var iso0 = state.selectedIso || state.pinned[0];
    var c0 = byIso[iso0];
    title = c0.country;
    var rk = rankOf(iso0, m.key);
    subtitle = m.mapLabel+', '+LATEST_YEAR+(rk ? ' · rank #'+rk.rank+' of '+rk.total : '');
  } else {
    var names = state.pinned.map(function(iso){ return byIso[iso].country; });
    title = names.length===2 ? names.join(' vs. ') : names.join(', ');
    subtitle = m.mapLabel+', '+LATEST_YEAR+' · '+m.legendUnit;
  }
  var ty = hy + H*0.085;
  var tSize = fitText(ctx, title, W-2*P, Math.round(H*0.062), '800', SANS);
  ctx.font = '800 '+tSize+'px '+SANS;
  ctx.fillStyle = pal.text;
  ctx.fillText(title, P, ty);
  ctx.font = '500 '+Math.round(H*0.026)+'px '+SANS;
  ctx.fillStyle = pal.muted;
  ctx.fillText(subtitle, P, ty + H*0.042);

  // content region
  var cy0 = ty + H*0.085, cy1 = H - P*1.45;

  if(view==='compare'){
    var isos = state.pinned;
    var max = d3.max(isos, function(iso){ return byIso[iso][m.key] || 0; });
    // cap the row height so a 2-country card clusters rows instead of
    // stranding them across the full canvas
    var rowH = Math.min((cy1-cy0)/isos.length, H*0.21);
    var rowsY0 = cy0 + Math.max(0, (cy1-cy0-rowH*isos.length)/2);
    var barMax = W - 2*P - W*0.30;
    isos.forEach(function(iso, i){
      var c = byIso[iso];
      var y = rowsY0 + rowH*i + rowH*0.18;
      ctx.beginPath(); ctx.arc(P+H*0.009, y-H*0.009, H*0.009, 0, Math.PI*2);
      ctx.fillStyle = pal.cats[i]; ctx.fill();
      ctx.font = '700 '+Math.round(H*0.03)+'px '+SANS;
      ctx.fillStyle = pal.text;
      ctx.fillText(c.country, P+H*0.028, y);
      var v = c[m.key];
      var by = y + rowH*0.16, bh = Math.min(H*0.034, rowH*0.3);
      ctx.fillStyle = pal.surface2;
      ctx.fillRect(P, by, barMax, bh);
      if(v!=null && max>0){
        ctx.fillStyle = pal.cats[i];
        ctx.fillRect(P, by, Math.max(barMax*(v/max), 3), bh);
      }
      ctx.font = '700 '+Math.round(H*0.032)+'px '+MONO;
      ctx.fillStyle = pal.text;
      ctx.textAlign = 'right';
      ctx.fillText(m.fmt(v), W-P, by+bh*0.9);
      ctx.textAlign = 'left';
      ctx.font = '400 '+Math.round(H*0.022)+'px '+SANS;
      ctx.fillStyle = pal.muted;
      ctx.fillText('Per person '+(c.co2_per_capita!=null?fmtNum(c.co2_per_capita,2)+' t':'—')
        +' · Share of warming '+fmtPct(c.share_of_temperature_change_from_ghg),
        P, by+bh+rowH*0.22);
    });
  } else {
    var mapRect = { x: W*0.42, y: cy0-H*0.02, w: W-P-W*0.42, h: cy1-cy0+H*0.02 };
    drawCardMap(ctx, mapRect, pal, theme);
    var statX = P, statW = W*0.34;
    var stats;
    if(view==='country'){
      var isoS = state.selectedIso || state.pinned[0];
      var cS = byIso[isoS];
      // the headline already shows the current metric; keep it out of the
      // small stats so the card never repeats a number
      var smallPool = [
        ['co2', 'CO₂, '+LATEST_YEAR, fmtMt(cS.co2)],
        ['co2_per_capita', 'Per person', cS.co2_per_capita!=null?fmtNum(cS.co2_per_capita,2)+' t':'—'],
        ['cumulative_co2', 'Cumulative since 1750', fmtMt(cS.cumulative_co2)],
        ['share_global_co2', 'Share of global CO₂', fmtPct(cS.share_global_co2)],
        ['share_of_temperature_change_from_ghg', 'Share of warming', fmtPct(cS.share_of_temperature_change_from_ghg)]
      ].filter(function(d){ return d[0]!==state.metric; }).slice(0,4);
      stats = [
        { big: m.fmt(cS[m.key]), label: m.mapLabel },
        { small: smallPool.map(function(d){ return [d[1], d[2]]; }) }
      ];
    } else {
      var topC = COUNTRIES.slice().filter(function(c){return c.co2!=null;}).sort(function(a,b){return b.co2-a.co2;})[0];
      stats = [
        { big: fmtMt(worldLatest.co2), label: 'Global CO₂ emissions, '+LATEST_YEAR },
        { small: [
          ['Average per person', fmtNum(worldLatest.co2_per_capita,2)+' t / yr'],
          ['Cumulative since 1750', fmtMt(worldLatest.cumulative_co2)],
          ['Warming from CO₂ so far', fmtC(worldLatest.temperature_change_from_co2)],
          ['Largest emitter', topC.country+' · '+fmtPct(topC.share_global_co2)]
        ]}
      ];
    }
    var sy = cy0 + H*0.055;
    ctx.font = '700 '+Math.round(H*0.075)+'px '+MONO;
    ctx.fillStyle = pal.text;
    ctx.fillText(stats[0].big, statX, sy);
    ctx.font = '500 '+Math.round(H*0.024)+'px '+SANS;
    ctx.fillStyle = pal.muted;
    ctx.fillText(stats[0].label, statX, sy+H*0.038);
    var gy = sy + H*0.105;
    stats[1].small.forEach(function(pair){
      ctx.font = '400 '+Math.round(H*0.022)+'px '+SANS;
      ctx.fillStyle = pal.muted;
      ctx.fillText(pair[0], statX, gy);
      ctx.font = '700 '+Math.round(H*0.03)+'px '+MONO;
      ctx.fillStyle = pal.text;
      ctx.fillText(pair[1], statX, gy+H*0.036);
      gy += H*0.088;
    });
  }

  // footer: hairline + two-line citation
  var fy = H - P*1.02;
  ctx.strokeStyle = pal.border; ctx.lineWidth = 1;
  ctx.beginPath(); ctx.moveTo(P, fy); ctx.lineTo(W-P, fy); ctx.stroke();
  ctx.font = '400 '+Math.round(H*0.021)+'px '+SANS;
  ctx.fillStyle = pal.muted;
  ctx.fillText('Data: Global Carbon Project via Our World in Data, owid/co2-data (CC BY 4.0)'
    + (META.generated ? ' · refreshed '+META.generated : ''), P, fy+H*0.036);
  ctx.font = '400 '+Math.round(H*0.021)+'px '+MONO;
  ctx.fillText(shortShareUrl(), P, fy+H*0.068);
  return cv;
}

var cardState = { canvas:null, filename:'' };
function openCardPreview(sizeKey){
  document.getElementById('share-popover').hidden = true;
  (document.fonts && document.fonts.ready ? document.fonts.ready : Promise.resolve()).then(function(){
    var cv = buildShareCard(sizeKey);
    var view = shareCardView();
    var slug = view==='country' ? (state.selectedIso||state.pinned[0]).toLowerCase()
      : view==='compare' ? state.pinned.join('-').toLowerCase() : 'world';
    cardState.canvas = cv;
    cardState.filename = 'carbon-ledger-'+slug+'-'+state.metric+'-'+LATEST_YEAR+'-'+sizeKey+'.png';
    document.getElementById('card-preview-img').src = cv.toDataURL('image/png');
    document.getElementById('card-preview-meta').textContent =
      cardState.filename+' · '+SHARE_SIZES[sizeKey].w+'×'+SHARE_SIZES[sizeKey].h+' px';
    document.getElementById('card-preview-hint').textContent =
      'You can also right-click the preview to copy or save it.';
    document.getElementById('card-overlay').hidden = false;
  });
}
document.getElementById('share-card-deck-btn').addEventListener('click', function(){ openCardPreview('deck'); });
document.getElementById('share-card-social-btn').addEventListener('click', function(){ openCardPreview('social'); });
document.getElementById('card-close-btn').addEventListener('click', function(){
  document.getElementById('card-overlay').hidden = true;
});
document.getElementById('card-overlay').addEventListener('click', function(e){
  if(e.target.id==='card-overlay') document.getElementById('card-overlay').hidden = true;
});
document.getElementById('card-download-btn').addEventListener('click', function(){
  if(!cardState.canvas) return;
  var btn = this;
  cardState.canvas.toBlob(function(blob){
    if(!blob) return;
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url; a.download = cardState.filename;
    document.body.appendChild(a); a.click(); document.body.removeChild(a);
    setTimeout(function(){ URL.revokeObjectURL(url); }, 1000);
    flashBtn(btn, 'Downloaded');
  }, 'image/png');
});
(function initCardCopy(){
  var btn = document.getElementById('card-copy-btn');
  if(!(navigator.clipboard && navigator.clipboard.write && window.ClipboardItem)){
    btn.hidden = true;
    return;
  }
  btn.addEventListener('click', function(){
    if(!cardState.canvas) return;
    cardState.canvas.toBlob(function(blob){
      if(!blob) return;
      navigator.clipboard.write([new ClipboardItem({'image/png': blob})])
        .then(function(){ flashBtn(btn, 'Copied'); },
              function(){ flashBtn(btn, 'Copy blocked'); });
    }, 'image/png');
  });
})();

