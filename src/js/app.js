/* ================= saved views + short view codes ================= */
// A view -- metric, pinned set, selection, scenario -- packs into a compact
// code like "w.CHN-USA..p50-2040" (metric . pins . selected . scenario),
// using only URL-safe literal characters. Short links
// carry it as ?v=<code>; saved views store the same code in localStorage, so
// one parser serves both.
var METRIC_CODES = { co2:'c', consumption_co2:'n', co2_per_capita:'p', cumulative_co2:'m',
  share_of_temperature_change_from_ghg:'w', fair_share_ratio:'f' };
var METRIC_FROM_CODE = {};
Object.keys(METRIC_CODES).forEach(function(k){ METRIC_FROM_CODE[METRIC_CODES[k]] = k; });
var GROUP_CODES = { top6:'t', pinned:'p', global:'g' };
var GROUP_FROM_CODE = { t:'top6', p:'pinned', g:'global' };
var SCENARIO_YEARS = [2030,2035,2040,2050];
var SCENARIO_DEFAULT = { group:'top6', reduction:30, year:2035 };

function scenarioIsDefault(){
  return scenarioState.group===SCENARIO_DEFAULT.group
    && scenarioState.reduction===SCENARIO_DEFAULT.reduction
    && scenarioState.year===SCENARIO_DEFAULT.year;
}
function encodeViewCode(){
  var seg1 = METRIC_CODES[state.metric];
  var seg4 = scenarioIsDefault() ? ''
    : GROUP_CODES[scenarioState.group]+scenarioState.reduction+'-'+scenarioState.year;
  return [seg1, state.pinned.join('-'), state.selectedIso||'', seg4]
    .join('.').replace(/\.+$/,'');
}
function decodeViewCode(code){
  if(!code) return null;
  var seg = String(code).split('.');
  // the [ld] theme suffix is legacy — accepted so old links parse, ignored
  var m1 = /^([cpmwfn])([ld])?$/.exec(seg[0]||'');
  if(!m1) return null;
  var v = { metric: METRIC_FROM_CODE[m1[1]], theme: null };
  v.pinned = (seg[1]||'').split('-').filter(function(iso,i,a){
    return byIso[iso] && byIso[iso].co2!=null && a.indexOf(iso)===i;
  }).slice(0, MAX_PINS);
  v.selected = (seg[2] && byIso[seg[2]]) ? seg[2] : null;
  v.scenario = null;
  var m4 = /^([tpg])(\d{1,3})-(\d{4})$/.exec(seg[3]||'');
  if(m4){
    var yr = +m4[3];
    v.scenario = {
      group: GROUP_FROM_CODE[m4[1]],
      reduction: Math.max(0, Math.min(100, +m4[2])),
      year: SCENARIO_YEARS.indexOf(yr)>-1 ? yr : SCENARIO_DEFAULT.year
    };
  }
  return v;
}
function applyDecodedView(v){
  state.metric = v.metric;
  state.pinned = v.pinned;
  state.selectedIso = v.selected;
  var sc = v.scenario || SCENARIO_DEFAULT;
  scenarioState.group = (sc.group==='pinned' && !v.pinned.length) ? 'top6' : sc.group;
  scenarioState.reduction = sc.reduction;
  scenarioState.year = sc.year;
  if(v.theme) applyThemeAttr(v.theme);
}
